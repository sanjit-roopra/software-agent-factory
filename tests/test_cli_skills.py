def test_generation_request_carries_only_the_profile_and_configured_sources(
    skill_repo: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Repository-level guidance is generated from the profile alone: no work
    item context, no changed files, no diff, and never from inside the
    repository or the operator's working directory."""
    data_dir = tmp_path / "data"
    captured: list[AgentRequest] = []

    def capture(request: AgentRequest) -> AgentResult:
        captured.append(request)
        return FakeAgentRuntime().run(request)

    _install_runtime(monkeypatch, FakeAgentRuntime(researcher=capture))
    result = _refresh(skill_repo, data_dir)

    assert result.exit_code == 0, result.output
    assert len(captured) == 1
    request = captured[0]
    assert request.role is AgentRole.RESEARCHER
    assert request.purpose is AgentPurpose.GENERATE_REPOSITORY_SKILL
    assert request.model == "gpt-5.6-sol"
    assert request.changed_files == []
    assert request.diff is None
    assert request.specification is None
    assert request.execution_plan is None
    assert request.change_set is None
    assert request.test_report is None
    assert request.verification_report is None
    assert request.repair_context is None
    assert request.attempt_number is None
    assert request.repository_profile is not None
    assert (
        request.repository_profile.dependency_fingerprint
        == profile_repository(skill_repo).dependency_fingerprint
    )
    assert "https://docs.pytest.org" in request.official_documentation_origins
    assert request.practice_reference_urls

    workspace = Path(request.workspace_path or "")
    assert workspace.is_dir()
    assert workspace.is_relative_to(data_dir / "skill-generation")
    assert not workspace.is_relative_to(skill_repo)


