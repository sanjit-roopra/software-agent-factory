def test_skill_path_is_identical_from_a_linked_worktree(
    skill_repo: Path, missing_data_dir: Path, tmp_path: Path
) -> None:
    """Identity is the Git *common* directory, so a worktree and its main
    checkout share one skill directory rather than generating twice."""
    worktree = tmp_path / "linked-worktree"
    _git(skill_repo, "worktree", "add", str(worktree), "-b", "topic")

    from_main = _skill_path(skill_repo, missing_data_dir)
    from_worktree = _skill_path(worktree, missing_data_dir)

    assert from_main.exit_code == 0, from_main.output
    assert from_worktree.exit_code == 0, from_worktree.output
    for prefix in ("repository key: ", "generated skill: ", "overlay: "):
        assert _line(from_main.output, prefix) == _line(from_worktree.output, prefix)
    assert not missing_data_dir.exists()


