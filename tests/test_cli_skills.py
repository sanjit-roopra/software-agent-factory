def test_refresh_creates_the_generated_skill_without_a_run_or_a_worktree(
    skill_repo: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    data_dir = tmp_path / "data"
    _install_runtime(monkeypatch, FakeAgentRuntime())

    result = _refresh(skill_repo, data_dir)

    assert result.exit_code == 0, result.output
    generated_path = _generated_path(skill_repo, data_dir)
    assert _line(result.output, "created generated skill: ").endswith(str(generated_path))
    stored = RepositorySkill.model_validate_json(generated_path.read_bytes())
    assert stored.dependency_fingerprint == profile_repository(skill_repo).dependency_fingerprint

    assert not (data_dir / "runs").exists()
    assert not (data_dir / "workspaces").exists()
    assert _git(skill_repo, "worktree", "list").strip().count("\n") == 0
    assert _git(skill_repo, "status", "--porcelain") == ""
    assert not _overlay_path(skill_repo, data_dir).exists()


def test_refresh_replaces_only_the_generated_file_and_never_the_overlay(
    skill_repo: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    data_dir = tmp_path / "data"
    _install_runtime(monkeypatch, FakeAgentRuntime())
    assert _refresh(skill_repo, data_dir).exit_code == 0

    generated_path = _generated_path(skill_repo, data_dir)
    first_bytes = generated_path.read_bytes()
    overlay_path = _overlay_path(skill_repo, data_dir)
    overlay_path.write_text(VALID_OVERLAY, encoding="utf-8")
    overlay_bytes = overlay_path.read_bytes()
    other_generated = generated_path.with_name(f"{'b' * 64}.json")
    other_generated.write_bytes(b"{}\n")

    result = _refresh(skill_repo, data_dir)

    assert result.exit_code == 0, result.output
    assert _line(result.output, "refreshed generated skill: ").endswith(str(generated_path))
    assert generated_path.read_bytes() != first_bytes  # restamped generated_at
    assert RepositorySkill.model_validate_json(generated_path.read_bytes())
    assert overlay_path.read_bytes() == overlay_bytes
    assert other_generated.read_bytes() == b"{}\n"
    assert sorted(p.name for p in generated_path.parent.iterdir()) == sorted(
        [generated_path.name, other_generated.name]
    )


