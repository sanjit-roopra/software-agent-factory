def _config_file(path: Path, data_dir: Path, *, polish_enabled: bool = True) -> Path:
    packaged = Path(software_agent_factory.__file__).parent / DEFAULT_CONFIG_FILENAME
    payload = yaml.safe_load(packaged.read_text(encoding="utf-8"))
    payload["factory"]["data_dir"] = str(data_dir)
    payload["polish"]["enabled"] = polish_enabled
    path.write_text(yaml.safe_dump(payload), encoding="utf-8")
    return path


def _install_runtime(monkeypatch: pytest.MonkeyPatch, runtime: FakeAgentRuntime) -> None:
    """Replace only the external model boundary the command would build."""
    monkeypatch.setattr(cli, "_build_runtime", lambda _choice: runtime)


def _refresh(repo: Path, data_dir: Path, *extra: str):
    return runner.invoke(
        cli.app, ["skill", "refresh", "--repo", str(repo), "--data-dir", str(data_dir), *extra]
    )


def _validate(repo: Path, data_dir: Path, *extra: str):
    return runner.invoke(
        cli.app, ["skill", "validate", "--repo", str(repo), "--data-dir", str(data_dir), *extra]
    )


def _skill_path(repo: Path, data_dir: Path, *extra: str):
    return runner.invoke(
        cli.app, ["skill", "path", "--repo", str(repo), "--data-dir", str(data_dir), *extra]
    )


def _line(output: str, prefix: str) -> str:
    for line in output.splitlines():
        if line.startswith(prefix):
            return line
    raise AssertionError(f"no {prefix!r} line in output:\n{output}")


def _generated_path(repo: Path, data_dir: Path) -> Path:
    fingerprint = profile_repository(repo).dependency_fingerprint
    key = _line(_skill_path(repo, data_dir).output, "repository key: ").split(": ", 1)[1]
    return data_dir / "repository-skills" / "v1" / key / "generated" / f"{fingerprint}.json"


def _overlay_path(repo: Path, data_dir: Path) -> Path:
    key = _line(_skill_path(repo, data_dir).output, "repository key: ").split(": ", 1)[1]
    return data_dir / "repository-skills" / "v1" / key / "repository-skill-overlay.yaml"


