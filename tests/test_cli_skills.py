def test_refresh_refuses_unverified_guidance_and_preserves_the_stored_skill(
    skill_repo: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    data_dir = tmp_path / "data"
    _install_runtime(monkeypatch, FakeAgentRuntime())
    assert _refresh(skill_repo, data_dir).exit_code == 0
    generated_path = _generated_path(skill_repo, data_dir)
    original = generated_path.read_bytes()

    def inventing(request: AgentRequest) -> AgentResult:
        profile = request.repository_profile
        assert profile is not None
        guidance = SkillGuidance(
            summary="Invented guidance.",
            guidance=("Use the newest release.",),
        )
        skill = RepositorySkill(
            dependency_fingerprint=profile.dependency_fingerprint,
            targets=(
                SkillTarget(
                    ecosystem="npm",
                    name="react",
                    declared_version="^19.1.0",
                    resolved_version="19.1.0",
                    evidence=("package.json",),
                ),
            ),
            official_sources=(
                SkillSource(
                    title="React documentation",
                    url="https://react.dev/reference/react",
                    version_scope="19.1.0",
                    applies_to=("react",),
                ),
            ),
            simplify=guidance,
            polish=guidance,
        )
        return AgentResult(role=AgentRole.RESEARCHER, success=True, repository_skill=skill)

    _install_runtime(monkeypatch, FakeAgentRuntime(researcher=inventing))
    result = _refresh(skill_repo, data_dir)

    assert result.exit_code == 1, result.output
    assert "refusing to store unverified repository guidance" in result.output
    assert "react" in result.output
    assert generated_path.read_bytes() == original


