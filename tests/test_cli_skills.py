def test_skill_path_reports_both_paths_without_creating_anything(
    skill_repo: Path, missing_data_dir: Path
) -> None:
    result = _skill_path(skill_repo, missing_data_dir)

    assert result.exit_code == 0, result.output
    fingerprint = profile_repository(skill_repo).dependency_fingerprint
    assert f"dependency fingerprint: {fingerprint}" in result.output
    assert _line(result.output, "repository key: ").split(": ", 1)[1]
    assert _line(result.output, "generated skill: ").endswith("(absent)")
    assert _line(result.output, "overlay: ").endswith("(absent)")
    assert f"{fingerprint}.json" in result.output
    assert "repository-skill-overlay.yaml" in result.output
    assert not missing_data_dir.exists()


