"""Tests for the human-facing ``factory skill`` commands.

Three properties are what these commands are *for*, so they are asserted
directly rather than implied:

- ``skill path`` and ``skill validate`` are read-only. They create nothing --
  not the data directory, not a generated file, not an overlay.
- ``skill refresh`` is the only write path, and it writes exactly one thing:
  the generated file for the current dependency fingerprint. It creates no
  run and no worktree, and never touches the human-owned overlay.
- A refusal (a failed researcher, unverified guidance) leaves the previously
  stored generated bytes exactly as they were.

Only the agent runtime -- the external model boundary -- is ever replaced;
the repository profiler, the skill manager, merging and validation are the
real implementations throughout.
"""

